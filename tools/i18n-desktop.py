KEYS = ('Name', 'GenericName', 'Comment', 'Keywords')


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read().split('\n')


def base_keywords(lines):
    for ln in lines:
        if ln.startswith('Keywords='):
            return ln[len('Keywords='):]
    return ''


def strip_generated(lines):
    """Drop the block this script wrote last time, so it is idempotent."""
    out, skipping = [], False
    for ln in lines:
        if ln.startswith('# Localised keys below are generated'):
            skipping = True
            continue
        if skipping:
            if ln.startswith('#') or re.match(r'^(Name|GenericName|Comment|Keywords)\[', ln):
                continue
            if ln.strip() == '':
                continue
            skipping = False
        out.append(ln)
    return out


def build(path, entry):
    lines = strip_generated(read(path))
    while lines and lines[-1].strip() == '':
        lines.pop()
    kw = base_keywords(lines)
    block = ['', MARK.rstrip('\n')]
    for key_i, key in enumerate(KEYS):
        for lang in LANGS:
            if lang not in entry:
                continue
            val = entry[lang][key_i]
            if not val:
                continue
            if key == 'Keywords':
                # Additive: the English list first, then the native terms.
                # Never a replacement -- see the header.
                if not kw:
                    continue
                val = kw + val
            block.append('%s[%s]=%s' % (key, lang, val))
    return '\n'.join(lines + block) + '\n'


def main():
    check = '--check' in sys.argv
    bad = 0
    done = 0
    for did, entry in sorted(D.items()):
        path = os.path.join(APPS, did + '.desktop')
        if not os.path.exists(path):
            print('ERROR: %s.desktop does not exist' % did, file=sys.stderr)
            bad = 1
            continue
        want = build(path, entry)
        with open(path, encoding='utf-8') as f:
            have = f.read()
        if have == want:
            done += 1
            continue
        if check:
            print('ERROR: %s.desktop is out of date — run: python3 tools/i18n-desktop.py'
                  % did, file=sys.stderr)
            bad = 1
        else:
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(want)
            print('  updated %s.desktop' % did)
            done += 1

    # Every shipped entry must be in the table. A new launcher entry that
    # nobody added here would ship English-only into an otherwise German
    # menu, and nothing else in the build would notice.
    have_files = {f[:-len('.desktop')] for f in os.listdir(APPS) if f.endswith('.desktop')}
    for missing in sorted(have_files - set(D)):
        print('ERROR: %s.desktop has no entry in tools/i18n-desktop.py' % missing,
              file=sys.stderr)
        bad = 1

    print('i18n-desktop: %d entries, %d languages each' % (done, len(LANGS)))
    return bad


if __name__ == '__main__':
    sys.exit(main())
