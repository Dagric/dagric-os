# Dagric OS -- write the localised keys into Dagric's own launcher entries.
#
#     python3 tools/i18n-desktop.py            update the .desktop files
#     python3 tools/i18n-desktop.py --check    verify only, change nothing
#
# WHY THIS IS NOT gettext
# -----------------------
# A .desktop file carries EVERY language at once:
#
#     Name=Migrate from Windows
#     Name[de]=Von Windows umziehen
#     Name[fr]=Migrer depuis Windows
#
# The desktop picks one by matching the LC_MESSAGES locale against the
# postfixes -- lang_COUNTRY@MOD, then lang_COUNTRY, then lang@MOD, then lang,
# then the unlocalised key. A locale with no entry falls back to the plain
# Name= with nothing to configure and nothing that can break. There is no
# runtime, no library and no catalogue lookup involved, which makes this the
# cheapest localisation win in the whole product -- and the reason the keys are
# written into the files rather than looked up.
#
# The file is the deliverable; this script is the maintainable source for it.
# Run it after editing any English Name/GenericName/Comment so the translations
# and the source cannot drift apart silently -- --check is what catches that.
#
# KEYWORDS ARE ADDITIVE, NEVER REPLACED
# -------------------------------------
# Keywords= is a search index, not prose, and it is the one field where machine
# translation reliably produces nonsense: "dolphin;explorer;this pc;" comes back
# with the fish and a literal "dieser PC", losing the actual German Windows
# terms a switcher would type. So Keywords[xx] is built as
#
#     the original English list  +  a short native list written by hand
#
# Nothing is ever taken away. A German owner can still find "Files" by typing
# "explorer" or "dolphin", and now also by typing "Dateien". If the native list
# for a language is empty, no Keywords[xx] is emitted at all and the English
# Keywords= applies -- which is exactly right, and is why the additions below
# are short and specific rather than a full translation of every term.
